import assert from "node:assert/strict";
import test from "node:test";
import { continuationHash, continuationJson, validateContinuationCheckpoint, type ContinuationCheckpoint } from "./continuation.ts";

const invalidJson = /Continuation data must be finite canonical JSON/;
function rejects(value: unknown, label: string) {
  assert.throws(() => continuationJson(value), invalidJson, label);
  assert.throws(() => continuationHash(value), invalidJson, label);
}
function checkpoint(result: unknown, resultHash: string, state: "ready" | "uncertain" = "ready"): ContinuationCheckpoint {
  return { unit: "fixture", kind: "fixture", inputHash: continuationHash({ input: 1 }), pipeline: 5, format: 1, state, sourceRunId: "fixture-run", result, resultHash };
}

test("ordinary JSON keeps exact pre-fix canonical bytes and SHA-256 hashes", () => {
  // Captured from the original canonicalizer, not generated by the code under test.
  const fixtures = [
    { value: null, json: "null", hash: "74234e98afe7498fb5daf1f36ac2d78acc339464f950703b8c019892f982b90b" },
    { value: "Unicode 😀\n\u0000", json: '"Unicode 😀\\n\\u0000"', hash: "2d38298709aff50abcf6c81821cb1e85cd07783506a13481f66adb599b810f72" },
    { value: [null, true, false, -0, 1.5, 1e30], json: "[null,true,false,0,1.5,1e+30]", hash: "8571eb0b4b00e16bf26aa3fdd4774702a58433f4ddf7ac7e89048c3107c1eafd" },
    { value: { z: [{ b: 2, a: 1 }, []], a: "ñ" }, json: '{"a":"ñ","z":[{"a":1,"b":2},[]]}', hash: "5121a2e5504d71f610ab3bca181df1f850e9c125e2a4bf793bf4aefd76b5798a" },
    { value: JSON.parse('{"2":"two","10":"ten","__proto__":{"z":1,"a":2},"constructor":true}'), json: '{"10":"ten","2":"two","__proto__":{"a":2,"z":1},"constructor":true}', hash: "dcb88e0b53518087f81922d6178c269dc75bb5adad0b37d046ed785aeeb8091f" },
  ];
  for (const { value, json, hash } of fixtures) {
    assert.equal(continuationJson(value), json);
    assert.equal(continuationHash(value), hash);
    validateContinuationCheckpoint(checkpoint(value, hash));
  }
  assert.equal(continuationJson("\ud800"), '"\\ud800"');
  for (const number of [Number.MIN_VALUE, Number.MAX_VALUE, Number.MIN_SAFE_INTEGER, Number.MAX_SAFE_INTEGER]) {
    assert.equal(continuationJson(number), JSON.stringify(number));
  }
});

test("ordering is recursive, deterministic and does not mutate shared or frozen JSON", () => {
  const first = { b: [{ y: 2, x: 1 }], a: 0 }, second = { a: 0, b: [{ x: 1, y: 2 }] };
  const before = structuredClone(first);
  assert.equal(continuationHash(first), continuationHash(second));
  assert.notEqual(continuationHash([1, 2]), continuationHash([2, 1]));
  const shared = Object.freeze({ b: 2, a: 1 });
  assert.equal(continuationJson(Object.freeze([shared, shared])), '[{"a":1,"b":2},{"a":1,"b":2}]');
  assert.equal(continuationHash({ left: shared, right: shared }), continuationHash({ left: { a: 1, b: 2 }, right: { b: 2, a: 1 } }));
  assert.deepEqual(first, before);
});

test("sparse arrays are rejected at every depth instead of colliding with dense results", () => {
  for (const value of [Array(1), Array(2), [1, , 2], { messages: Array(1) }, [[Array(1)]]]) rejects(value, "sparse array");
  const compensated = Array(1); Object.assign(compensated, { extra: true });
  rejects(compensated, "an extra key cannot compensate for a missing index");
  const inherited = Array(1); Object.setPrototypeOf(inherited, { 0: "inherited" });
  rejects(inherited, "inherited indices are not durable array data");
  assert.equal(continuationJson([]), "[]");
  assert.equal(continuationJson([null]), "[null]");
});

test("extra array keys, symbols and non-enumerable properties cannot disappear", () => {
  for (const key of ["extra", "-1", "01", "1.0", "4294967295", Symbol("extra")]) {
    const value = [1]; Object.defineProperty(value, key, { value: true, enumerable: true });
    rejects(value, String(key)); rejects({ nested: value }, String(key));
  }
  for (const enumerable of [false, true]) {
    const value = { ordinary: true }; Object.defineProperty(value, Symbol("hidden"), { value: null, enumerable });
    rejects(value, "object symbol");
  }
  for (const value of [{}, []]) {
    Object.defineProperty(value, "hidden", { value: null }); rejects(value, "non-enumerable property");
  }
  const index = [1]; Object.defineProperty(index, "0", { enumerable: false });
  rejects(index, "non-enumerable array index");
});

test("undefined, functions, bigint, symbols and nonfinite numbers reject at every depth", () => {
  for (const value of [undefined, () => 1, 1n, Symbol("value"), NaN, Infinity, -Infinity]) {
    rejects(value, typeof value); rejects([value], "array value"); rejects({ nested: { value } }, "nested value");
  }
});

test("nonplain objects and nonordinary array prototypes are not JSON", () => {
  class Example { value = 1; }
  class ExampleArray extends Array {}
  for (const value of [new Date(), new Map(), new Set(), /x/, new Uint8Array([1]), new Number(1), new Example(), Object.create(null), new ExampleArray(1), Object.setPrototypeOf([], null)]) {
    rejects(value, "nonplain value"); rejects({ nested: value }, "nested nonplain value");
  }
});

test("cycles reject deliberately while noncyclic shared references remain valid", () => {
  const object: Record<string, unknown> = {}; object.self = object;
  const array: unknown[] = []; array.push(array);
  const mixed: { nested: unknown[] } = { nested: [] }; mixed.nested.push({ back: mixed });
  for (const value of [object, array, mixed]) rejects(value, "cycle");
  assert.equal(continuationJson({ subsequent: true }), '{"subsequent":true}');
});

test("accessors, toJSON and proxies reject without executing getters, hooks or traps", () => {
  let effects = 0;
  const forbidden = () => { effects++; throw new Error("unexpected effect"); };
  for (const value of [{}, [1]]) for (const descriptor of [
    { enumerable: true, get: forbidden }, { enumerable: true, set: forbidden }, { get: forbidden },
  ]) {
    const target = Array.isArray(value) ? [1] : {};
    Object.defineProperty(target, Array.isArray(target) ? "0" : "value", descriptor);
    const before = Object.getOwnPropertyDescriptors(target);
    rejects(target, "accessor");
    assert.deepEqual(Object.getOwnPropertyDescriptors(target), before);
  }
  rejects({ toJSON: forbidden }, "toJSON method");
  rejects(Object.defineProperty({}, "toJSON", { get: forbidden }), "toJSON getter");
  const handler = { get: forbidden, getPrototypeOf: forbidden, ownKeys: forbidden, getOwnPropertyDescriptor: forbidden };
  for (const value of [{}, []]) rejects(new Proxy(value, handler), "proxy");
  const revoked = Proxy.revocable({}, handler); revoked.revoke(); rejects(revoked.proxy, "revoked proxy");
  assert.equal(effects, 0);
});

test("ready and uncertain checkpoints reject sparse/hidden inline data with the old lossy hash", () => {
  for (const state of ["ready", "uncertain"] as const) {
    const sparse = checkpoint(Array(1), continuationHash([]), state);
    assert.throws(() => validateContinuationCheckpoint(sparse), invalidJson, "confirmed sparse checkpoint reproduction");
    for (const result of [[], { messages: [] }]) {
      const hash = continuationHash(result);
      const target = Array.isArray(result) ? result : result.messages;
      for (const key of ["extra", Symbol("hidden")]) {
        const changed = structuredClone(result), changedTarget = Array.isArray(changed) ? changed : changed.messages;
        Object.defineProperty(changedTarget, key, { value: true, enumerable: true });
        assert.throws(() => validateContinuationCheckpoint(checkpoint(changed, hash, state)), invalidJson);
      }
      Object.defineProperty(target, "hidden", { value: true });
      assert.throws(() => validateContinuationCheckpoint(checkpoint(result, hash, state)), invalidJson);
    }
    for (const result of [{ value: undefined }, [NaN], 1n, { value: () => 1 }]) {
      assert.throws(() => validateContinuationCheckpoint(checkpoint(result, "0".repeat(64), state)), invalidJson);
    }
  }
});

test("checkpoint envelopes validate JSON before reading fields or invoking result accessors", () => {
  let effects = 0;
  const forbidden = () => { effects++; throw new Error("unexpected checkpoint effect"); };
  for (const key of ["unit", "result", "resultHash", "sourceRunId"]) {
    const value = checkpoint({}, continuationHash({}));
    Object.defineProperty(value, key, { enumerable: true, get: forbidden });
    assert.throws(() => validateContinuationCheckpoint(value), invalidJson);
  }
  const proxied = new Proxy(checkpoint({}, continuationHash({})), { get: forbidden, ownKeys: forbidden, getPrototypeOf: forbidden });
  assert.throws(() => validateContinuationCheckpoint(proxied), invalidJson);
  for (const key of ["hidden", Symbol("hidden")]) {
    const value = checkpoint({}, continuationHash({})); Object.defineProperty(value, key, { value: true });
    assert.throws(() => validateContinuationCheckpoint(value), invalidJson);
  }
  assert.equal(effects, 0);
});

test("hash, envelope and referenced-checkpoint guards remain strict", () => {
  const valid = checkpoint({ value: 1 }, continuationHash({ value: 1 }));
  validateContinuationCheckpoint(valid);
  assert.throws(() => validateContinuationCheckpoint({ ...valid, resultHash: "0".repeat(64) }), /verified hash/);
  assert.throws(() => validateContinuationCheckpoint({ ...valid, resultRef: "unverified/path" }), /referenced checkpoints are blocked/);
  assert.throws(() => validateContinuationCheckpoint({ ...valid, pipeline: 0 as 5 }), /Invalid continuation checkpoint envelope/);
  const { result, resultHash, ...empty } = valid;
  assert.throws(() => validateContinuationCheckpoint(empty), /verified hash/);
  validateContinuationCheckpoint({ ...empty, state: "uncertain" });
  assert.throws(() => validateContinuationCheckpoint({ ...empty, state: "uncertain", result: undefined }), invalidJson);
});
